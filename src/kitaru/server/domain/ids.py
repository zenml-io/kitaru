"""Time-ordered id generation."""

import uuid

import uuid_utils


def uuid7() -> uuid.UUID:
    """Generate a UUIDv7.

    Returns:
        Time-ordered UUID.
    """
    return uuid.UUID(bytes=uuid_utils.uuid7().bytes)
