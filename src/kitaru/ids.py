"""Time-ordered id generation for producers of session nodes."""

import secrets
import time
import uuid


def uuid7() -> uuid.UUID:
    """Generate a UUIDv7.

    Returns:
        Time-ordered UUID.
    """
    value = (time.time_ns() // 1_000_000) << 80
    value |= 0x7 << 76
    value |= secrets.randbits(12) << 64
    value |= 0b10 << 62
    value |= secrets.randbits(62)
    return uuid.UUID(int=value)
